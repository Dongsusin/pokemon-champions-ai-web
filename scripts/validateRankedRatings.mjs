import assert from 'node:assert/strict'
import { createRankedProfile, getRankedTier, settleRankedRatings } from '../src/data/rankedRules.js'

const initial = createRankedProfile()
const result = settleRankedRatings(initial, initial, 'win')
assert.deepEqual(result.changes, { a: { points: 30, rating: 16 }, b: { points: 0, rating: -16 } })
assert.equal(result.a.wins, 1)
assert.equal(result.b.losses, 1)
assert.equal(initial.played, 0, 'settlement must not mutate the prior profile')
assert.equal(getRankedTier(0).label, '몬스터볼 IV')
assert.equal(getRankedTier(99).label, '몬스터볼 IV')
assert.equal(getRankedTier(100).label, '몬스터볼 III')
assert.equal(getRankedTier(399).label, '몬스터볼 I')
assert.equal(getRankedTier(400).label, '슈퍼볼 IV')
assert.equal(getRankedTier(800).label, '하이퍼볼 IV')
assert.equal(getRankedTier(1200).label, '마스터볼')
assert.equal(getRankedTier(1200).nextPoints, null)
assert.equal(getRankedTier(350).progress, 0.5)
assert.equal(getRankedTier(NaN).label, '몬스터볼 IV')
const promotion = settleRankedRatings({ ...initial, points: 390 }, initial, 'win')
assert.equal(getRankedTier(promotion.a.points).label, '슈퍼볼 IV')
const demotion = settleRankedRatings({ ...initial, points: 400 }, initial, 'loss')
assert.equal(getRankedTier(demotion.a.points).label, '몬스터볼 I')
const upset = settleRankedRatings({ ...initial, rating: 800 }, { ...initial, rating: 1600 }, 'win')
assert(upset.changes.a.rating > result.changes.a.rating)
assert.equal(upset.changes.a.rating + upset.changes.b.rating, 0)
const draw = settleRankedRatings(initial, initial, 'draw')
assert.equal(draw.a.points, 0)
assert.equal(draw.a.rating, 1000)
assert.equal(draw.a.draws, 1)
assert.equal(draw.b.draws, 1)
assert.throws(() => settleRankedRatings(initial, createRankedProfile('double'), 'win'))
assert.throws(() => settleRankedRatings(initial, initial, 'invented'))
console.log('PASS ranked tier boundaries, promotion/demotion, Elo upset, draw, format isolation and immutability')
