function hashText(value) {
  let hash = 2166136261
  for (const character of String(value)) {
    hash ^= character.codePointAt(0)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

function findVoiceGroup(trainer) {
  const namedGroup = VOICE_GROUPS.find((group) => group.names.has(trainer?.name))
  if (namedGroup) return namedGroup
  if (trainer?.tier === 'S' || trainer?.tier === 'A') return VOICE_GROUPS.find((group) => group.id === 'champion')
  return null
}

function interpolateDialogue(template, trainer, context) {
  const specialty = context.specialty ?? trainer?.specialties?.[0] ?? null
  const ace = context.aceName ?? trainer?.ace?.name ?? context.activeName ?? '에이스'
  const active = context.activeName ?? ace
  const typePlan = TYPE_THEMES[specialty] ?? (specialty ? `${specialty} 타입의 흐름` : '우리 팀의 흐름')

  return String(template)
    .replaceAll('{trainer}', trainer?.name ?? '트레이너')
    .replaceAll('{ace}', ace)
    .replaceAll('{active}', active)
    .replaceAll('{type}', specialty ?? '주력')
    .replaceAll('{typePlan}', typePlan)
}

export function getTrainerDialogue(trainer, eventId, context = {}) {
  const event = EVENT_META[eventId] ? eventId : TRAINER_DIALOGUE_EVENTS.MID
  const curated = CURATED_DIALOGUES[trainer?.name]?.[event]
  const voiceGroup = findVoiceGroup(trainer)
  const candidates = curated
    ? [curated]
    : voiceGroup?.lines?.[event] ?? DEFAULT_LINES[event]
  const seed = hashText(`${trainer?.id ?? trainer?.name ?? 'trainer'}:${event}:${context.turn ?? 0}`)
  const template = candidates[seed % candidates.length]

  return {
    id: `${trainer?.id ?? trainer?.name ?? 'trainer'}-${event}-${context.turn ?? 0}`,
    eventId: event,
    label: EVENT_META[event].label,
    caption: EVENT_META[event].caption,
    tone: EVENT_META[event].tone,
    trainerName: trainer?.name ?? '트레이너',
    text: interpolateDialogue(template, trainer, context),
  }
}

export function getTrainerDialogueEventMeta(eventId) {
  return EVENT_META[eventId] ?? EVENT_META.mid
}
